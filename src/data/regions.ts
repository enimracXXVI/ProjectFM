/** True when the given regions form one connected block of bordering regions. */
export function areContiguous(regionIds: string[], regions: Region[]): boolean {
  if (regionIds.length <= 1) return true
  const wanted = new Set(regionIds)
  const byId = new Map(regions.map((r) => [r.id, r]))
  const seen = new Set([regionIds[0]])
  const queue = [regionIds[0]]
  while (queue.length) {
    const r = byId.get(queue.shift()!)
    for (const n of r?.neighbours ?? []) {
      if (wanted.has(n) && !seen.has(n)) {
        seen.add(n)
        queue.push(n)
      }
    }
  }
  return seen.size === wanted.size
}
